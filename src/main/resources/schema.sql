-- =====================================================================
--  ИС «SpaceMarine» — схема БД (PostgreSQL, база studs на pg)
--  Версия для ЛР2: пользователи, владельцы орденов, история импорта.
--  Скрипт идемпотентный: можно запускать повторно (всё пересоздаётся,
--  ДАННЫЕ УДАЛЯЮТСЯ!).
--  Запуск:  psql -h pg -d studs -f schema.sql
--
--  ВАЖНО про уникальность (требование ЛР2). Ограничения предметной области
--    * название ордена уникально без учёта регистра;
--    * пара координат (x, y) уникальна;
--    * нельзя создать полный дубль десантника
--  проверяются ТОЛЬКО в бизнес-логике приложения. Поэтому здесь нет
--  UNIQUE-ограничений и уникальных индексов на chapter.name,
--  coordinates(x, y) и полях space_marine — это сделано намеренно.
--  UNIQUE на app_user.login — техническое ограничение учётных записей,
--  к ограничениям предметной области оно не относится.
-- =====================================================================

-- ---------- очистка ----------
DROP FUNCTION IF EXISTS sm_sum_heart_count();
DROP FUNCTION IF EXISTS sm_group_by_melee_weapon();
DROP FUNCTION IF EXISTS sm_find_by_name_substring(TEXT);
DROP FUNCTION IF EXISTS sm_create_chapter(TEXT, BIGINT);           -- версия ЛР1
DROP FUNCTION IF EXISTS sm_create_chapter(TEXT, BIGINT, INTEGER);
DROP FUNCTION IF EXISTS sm_disband_chapter(INTEGER);

DROP TABLE IF EXISTS import_operation;
DROP TABLE IF EXISTS space_marine;
DROP TABLE IF EXISTS coordinates;
DROP TABLE IF EXISTS chapter;
DROP TABLE IF EXISTS auth_session;
DROP TABLE IF EXISTS app_user;

-- =====================================================================
--  Пользователи
-- =====================================================================

-- USER  — командующий: управляет своими орденами и их десантниками;
-- ADMIN — главнокомандующий: может изменять и удалять любые объекты.
CREATE TABLE app_user (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         VARCHAR(50)  NOT NULL UNIQUE,
    -- формат: pbkdf2_sha256$<итерации>$<соль base64>$<хэш base64>
    password_hash VARCHAR(200) NOT NULL,
    role          VARCHAR(10)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT app_user_role_enum CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT app_user_login_format CHECK (login ~ '^[A-Za-z0-9_.-]{3,50}$')
);

-- Сессии входа. Клиент хранит случайный токен, в БД лежит только его
-- SHA-256 — утечка таблицы не даёт войти под чужим именем.
CREATE TABLE auth_session (
    token_hash CHAR(64) PRIMARY KEY,
    user_id    INTEGER  NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX auth_session_user_idx ON auth_session (user_id);

-- =====================================================================
--  Предметная область
-- =====================================================================

-- ---------- Chapter ----------
-- owner_id — командующий ордена. Владелец десантника не хранится отдельно:
-- это владелец его ордена (space_marine.chapter_id -> chapter.owner_id).
CREATE TABLE chapter (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    marines_count BIGINT       NOT NULL,
    owner_id      INTEGER      NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    version       BIGINT       NOT NULL DEFAULT 0,  -- оптимистическая блокировка (@Version)
    CONSTRAINT chapter_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT chapter_marines_count_range CHECK (marines_count > 0 AND marines_count <= 1000)
);
CREATE INDEX chapter_owner_idx ON chapter (owner_id);

-- ---------- Coordinates ----------
-- Общие для всех пользователей: точка в общем пространстве.
-- Создавать может любой вошедший пользователь, менять и удалять — только ADMIN.
CREATE TABLE coordinates (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x       BIGINT           NOT NULL,
    y       DOUBLE PRECISION NOT NULL,
    version BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT coordinates_y_min CHECK (y > -833)
);

-- ---------- SpaceMarine ----------
CREATE TABLE space_marine (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    coordinates_id INTEGER      NOT NULL REFERENCES coordinates (id) ON DELETE RESTRICT,
    creation_date  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    chapter_id     INTEGER      NOT NULL REFERENCES chapter (id) ON DELETE RESTRICT,
    health         BIGINT       NOT NULL,
    heart_count    INTEGER,
    height         INTEGER      NOT NULL,
    melee_weapon   VARCHAR(20),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT space_marine_id_positive   CHECK (id > 0),
    CONSTRAINT space_marine_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT space_marine_health_positive CHECK (health > 0),
    CONSTRAINT space_marine_heart_count_range
        CHECK (heart_count IS NULL OR (heart_count > 0 AND heart_count <= 3)),
    CONSTRAINT space_marine_melee_weapon_enum
        CHECK (melee_weapon IS NULL
               OR melee_weapon IN ('CHAIN_SWORD', 'POWER_SWORD', 'CHAIN_AXE', 'POWER_FIST'))
);

-- индексы под фильтрацию/сортировку и связи (НЕ уникальные)
CREATE INDEX space_marine_name_idx         ON space_marine (name);
CREATE INDEX space_marine_chapter_idx      ON space_marine (chapter_id);
CREATE INDEX space_marine_coordinates_idx  ON space_marine (coordinates_id);
CREATE INDEX space_marine_melee_weapon_idx ON space_marine (melee_weapon);

-- =====================================================================
--  История импорта
-- =====================================================================
-- Запись создаётся в отдельной транзакции до начала импорта (IN_PROGRESS)
-- и обновляется в отдельной транзакции после него (SUCCESS / FAILED),
-- поэтому сохраняется и тогда, когда сам импорт откатился.
CREATE TABLE import_operation (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'IN_PROGRESS',
    file_name     VARCHAR(255),
    added_count   INTEGER,         -- только для SUCCESS
    skipped_count INTEGER,         -- пропущенные полные дубли своих десантников
    error_message TEXT,            -- только для FAILED
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    finished_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT import_status_enum CHECK (status IN ('IN_PROGRESS', 'SUCCESS', 'FAILED')),
    CONSTRAINT import_counts_non_negative
        CHECK ((added_count IS NULL OR added_count >= 0) AND (skipped_count IS NULL OR skipped_count >= 0)),
    CONSTRAINT import_success_has_count
        CHECK (status <> 'SUCCESS' OR added_count IS NOT NULL),
    CONSTRAINT import_finished_has_time
        CHECK (status = 'IN_PROGRESS' OR finished_at IS NOT NULL)
);
CREATE INDEX import_operation_user_idx ON import_operation (user_id, id DESC);

-- =====================================================================
--  Специальные операции (вызываются из service через native query).
--  Проверки прав (кто может распустить орден) выполняются в Java до вызова.
-- =====================================================================

-- 1. Сумма heartCount по всем объектам (NULL не учитываются; пусто -> 0)
CREATE FUNCTION sm_sum_heart_count()
RETURNS BIGINT
LANGUAGE sql STABLE AS
$$
    SELECT COALESCE(SUM(heart_count), 0)::BIGINT FROM space_marine;
$$;

-- 2. Группировка по meleeWeapon: количество в каждой группе (включая NULL)
CREATE FUNCTION sm_group_by_melee_weapon()
RETURNS TABLE (melee_weapon VARCHAR, cnt BIGINT)
LANGUAGE sql STABLE AS
$$
    SELECT sm.melee_weapon, COUNT(*)::BIGINT
    FROM space_marine sm
    GROUP BY sm.melee_weapon
    ORDER BY sm.melee_weapon NULLS LAST;
$$;

-- 3. Объекты, у которых name содержит подстроку (без учёта %/_ как шаблонов)
CREATE FUNCTION sm_find_by_name_substring(p_substring TEXT)
RETURNS SETOF space_marine
LANGUAGE sql STABLE AS
$$
    SELECT * FROM space_marine
    WHERE strpos(name, p_substring) > 0
    ORDER BY id;
$$;

-- 4. Создать новый орден для командующего p_owner_id, вернуть его id.
--    Уникальность названия здесь НЕ проверяется — это делает бизнес-логика
--    перед вызовом функции.
CREATE FUNCTION sm_create_chapter(p_name TEXT, p_marines_count BIGINT, p_owner_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql AS
$$
DECLARE
    v_id INTEGER;
BEGIN
    IF p_name IS NULL OR btrim(p_name) = '' THEN
        RAISE EXCEPTION 'Имя ордена не может быть пустым' USING ERRCODE = '22023';
    END IF;
    IF p_marines_count IS NULL OR p_marines_count <= 0 OR p_marines_count > 1000 THEN
        RAISE EXCEPTION 'marinesCount должен быть в диапазоне 1..1000' USING ERRCODE = '22023';
    END IF;
    IF p_owner_id IS NULL OR NOT EXISTS (SELECT 1 FROM app_user WHERE id = p_owner_id) THEN
        RAISE EXCEPTION 'Пользователь с id=% не найден', p_owner_id USING ERRCODE = '22023';
    END IF;

    INSERT INTO chapter (name, marines_count, owner_id)
    VALUES (p_name, p_marines_count, p_owner_id)
    RETURNING id INTO v_id;

    RETURN v_id;
END;
$$;

-- 5. Распустить орден: удалить всех его десантников и сам орден.
--    Возвращает число удалённых десантников. Координаты не трогаем —
--    это общие объекты, их можно переиспользовать.
CREATE FUNCTION sm_disband_chapter(p_chapter_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql AS
$$
DECLARE
    v_deleted INTEGER;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM chapter WHERE id = p_chapter_id) THEN
        RAISE EXCEPTION 'Орден с id=% не найден', p_chapter_id USING ERRCODE = 'P0002';
    END IF;

    DELETE FROM space_marine WHERE chapter_id = p_chapter_id;
    GET DIAGNOSTICS v_deleted = ROW_COUNT;

    DELETE FROM chapter WHERE id = p_chapter_id;

    RETURN v_deleted;
END;
$$;

